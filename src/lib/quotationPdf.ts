// Quotation PDF, built on the phone from the SERVER's saved quotation (never
// from the live-preview maths) and handed to the OS share sheet.
//
// "WhatsApp pe PDF bhejo" opens Sharing.shareAsync: expo-sharing cannot
// target one app with a file, so the user picks WhatsApp in the sheet. A
// backend-rendered PDF can replace the HTML builder later (3=c); the share
// step stays the same.
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import * as FileSystem from 'expo-file-system';
import type { Quotation } from './api';
import { formatDateIN, formatINR, formatIndianNumber } from './inr';
import { isSafeHttpUrl } from './safeUrl';

/** Every user-typed string in the HTML goes through this (& < > " '). */
export function escapeHtml(s: unknown): string {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/** Escaped, with newlines kept as <br/> (payment plans and terms are multi-line). */
const text = (s: unknown) => escapeHtml(s).replace(/\r\n|\n|\r/g, '<br/>');

const row = (label: string, amount: string, cls = '') =>
  `<tr${cls ? ` class="${cls}"` : ''}><td>${label}</td><td class="amt">${amount}</td></tr>`;

const section = (title: string, body: string) => `<div class="section"><h3>${escapeHtml(title)}</h3>${body}</div>`;

export function buildQuotationHtml(q: Quotation): string {
  const s = q.sender || ({} as Quotation['sender']);
  const p = q.projectSnapshot || {};
  const u = q.unit || ({} as Quotation['unit']);
  const b = q.buyer || ({} as Quotation['buyer']);
  const totals = q.totals;

  const logo = isSafeHttpUrl(s.logoUrl) ? `<img class="logo" src="${escapeHtml(s.logoUrl)}" alt=""/>` : '';
  const senderLines = [s.designation, s.companyName, s.phone, s.email].filter(Boolean).map((v) => `<div>${escapeHtml(v)}</div>`).join('');
  const header = `<div class="header">${logo}<div><div class="sender-name">${escapeHtml(s.name)}</div>${senderLines}</div></div>`;

  const title = `<div class="title"><h1>Quotation</h1><div>${escapeHtml(q.number)} · ${escapeHtml(formatDateIN(q.createdAt))}</div></div>`;

  const place = [p.location, p.city].filter(Boolean).map(escapeHtml).join(', ');
  const projectBlock = section(
    'Project',
    `<div class="strong">${escapeHtml(p.projectName)}</div>` +
      (place ? `<div>${place}</div>` : '') +
      (p.builderName ? `<div>Builder: ${escapeHtml(p.builderName)}</div>` : '') +
      (p.reraNumber ? `<div>RERA: ${escapeHtml(p.reraNumber)}</div>` : ''),
  );

  const flatBits = [
    u.label ? `Flat ${escapeHtml(u.label)}` : '',
    u.tower ? `Tower ${escapeHtml(u.tower)}` : '',
    u.floor !== null && u.floor !== undefined ? `Floor ${escapeHtml(u.floor)}` : '',
    u.bhk ? escapeHtml(u.bhk) : '',
  ].filter(Boolean).join(' · ');
  const carpet = `Carpet ${formatIndianNumber(q.inputs?.carpetSqFt)} sq.ft @ ${formatINR(q.inputs?.ratePerSqFt)}/sq.ft`;
  const buyerBits = [b.name, b.phone].filter(Boolean).map(escapeHtml).join(' · ');
  const flatBlock = section(
    'Flat & buyer',
    (flatBits ? `<div>${flatBits}</div>` : '') + `<div>${carpet}</div>` + (buyerBits ? `<div>Buyer: ${buyerBits}</div>` : ''),
  );

  // The server only adds a `discount` line when discount > 0, but the row is
  // keyed off totals so a ₹0 discount row can never print (2=b).
  const costRows =
    (q.lines || []).filter((l) => l.key !== 'discount').map((l) => row(escapeHtml(l.label), formatINR(l.amount))).join('') +
    (totals.discount > 0 ? row('Discount', formatINR(-totals.discount), 'discount') : '') +
    row('Agreement value', formatINR(totals.agreementValue), 'subtotal');
  const costBlock = section('Cost sheet', `<table>${costRows}</table>`);

  const taxRows =
    (q.taxes || []).map((t) => row(escapeHtml(t.label), formatINR(t.amount))).join('') +
    row('Grand total', formatINR(totals.grandTotal), 'grand');
  const taxBlock = section('Taxes & charges', `<table>${taxRows}</table>`);

  const optional = [
    q.paymentPlan ? section('Payment plan', `<div class="pre">${text(q.paymentPlan)}</div>`) : '',
    q.remarks ? section('Remarks', `<div class="pre">${text(q.remarks)}</div>`) : '',
    q.notes?.length ? section('Notes', q.notes.map((n) => `<div class="note">${text(n)}</div>`).join('')) : '',
    q.termsText ? section('Terms', `<div class="pre">${text(q.termsText)}</div>`) : '',
    q.bankDetails ? section('Bank details', `<div class="pre">${text(q.bankDetails)}</div>`) : '',
  ].join('');

  const footer = `<div class="footer">Valid till ${escapeHtml(formatDateIN(q.validUntil))} · ${escapeHtml(q.number)} · Generated by HomeInTown</div>`;

  return `<!DOCTYPE html><html><head><meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<style>
  @page { size: A4; margin: 16mm 14mm; }
  body { font-family: -apple-system, Roboto, 'Helvetica Neue', Arial, sans-serif; color: #1C1917; font-size: 12px; margin: 0; }
  .header { display: flex; align-items: center; gap: 12px; border-bottom: 3px solid #B45309; padding-bottom: 10px; }
  .logo { width: 56px; height: 56px; object-fit: contain; }
  .sender-name { font-size: 16px; font-weight: 700; }
  .title { display: flex; justify-content: space-between; align-items: baseline; margin: 14px 0 6px; }
  .title h1 { color: #B45309; font-size: 22px; margin: 0; }
  .section { margin-top: 12px; }
  .section h3 { font-size: 12px; text-transform: uppercase; letter-spacing: 0.5px; color: #B45309; margin: 0 0 4px; }
  .strong { font-weight: 700; font-size: 14px; }
  table { width: 100%; border-collapse: collapse; }
  td { border: 1px solid #E7E5E4; padding: 6px 8px; }
  td.amt { text-align: right; white-space: nowrap; width: 32%; }
  tr.discount td { color: #15803D; }
  tr.subtotal td { font-weight: 700; background: #FAFAF9; }
  tr.grand td { font-weight: 700; font-size: 14px; background: #FFF7ED; border-top: 2px solid #B45309; }
  .pre { white-space: normal; }
  .note { color: #57534E; font-size: 11px; }
  .footer { margin-top: 18px; padding-top: 8px; border-top: 1px solid #E7E5E4; color: #78716C; font-size: 10px; text-align: center; }
</style></head><body>
${header}${title}${projectBlock}${flatBlock}${costBlock}${taxBlock}${optional}${footer}
</body></html>`;
}

/** "Quotation-HIT-Q-2026-0001.pdf"; anything outside [A-Za-z0-9._-] becomes _. */
export function quotationFileName(q: Pick<Quotation, 'number'>): string {
  return `Quotation-${String(q.number || 'draft')}.pdf`.replace(/[^A-Za-z0-9._-]/g, '_');
}

/**
 * Render the PDF, rename it to Quotation-<number>.pdf in the cache (WhatsApp
 * shows the file name, and printToFileAsync's is a random UUID) and open the
 * share sheet. Returns the file uri.
 */
export async function shareQuotationPdf(q: Quotation): Promise<string> {
  const { uri } = await Print.printToFileAsync({ html: buildQuotationHtml(q) });
  const target = `${FileSystem.cacheDirectory}${quotationFileName(q)}`;
  // Re-sharing the same quotation must overwrite, not fail on "file exists".
  await FileSystem.deleteAsync(target, { idempotent: true });
  await FileSystem.moveAsync({ from: uri, to: target });
  if (!(await Sharing.isAvailableAsync())) throw new Error('Sharing is not available on this device');
  await Sharing.shareAsync(target, {
    mimeType: 'application/pdf',
    UTI: 'com.adobe.pdf',
    dialogTitle: `Quotation ${q.number}`,
  });
  return target;
}
